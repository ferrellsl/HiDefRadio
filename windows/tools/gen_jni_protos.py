"""Writes src/engine_jni.h: prototypes of the engine's JNI entry points in native-lib.cpp."""
import re, sys
src = open(sys.argv[1], encoding="utf-8").read()
out = ["// Generated by tools/gen_jni_protos.py from the Android app's native-lib.cpp. Do not edit.",
       "#pragma once", "#include <jni.h>", ""]
for m in re.finditer(r'extern "C" JNIEXPORT (\w+) JNICALL\s*\n(Java_\w+)\s*\(([^)]*)\)', src):
    ret, name, args = m.groups()
    args = re.sub(r'/\*.*?\*/', '', args)
    args = " ".join(args.split())
    out.append(f'extern "C" {ret} {name}({args});')
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
print(len(out) - 4, "prototypes")
